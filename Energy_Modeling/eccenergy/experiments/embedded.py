"""embedded: Task 2 -- embedded ECC, DRAM energy effect only. One JSON per architecture.

    bash run.sh embedded --eval                  # evaluation only: cached mappings, no mapper
    bash run.sh embedded --layers "layer3.0.downsample.0 layer4.1.conv2" --eval
    bash hpc/tl.sh bash run.sh embedded --eval   # HiPerGator (the host python has no pandas)

WHAT IT COMPUTES
----------------
Two evaluated variants, side by side in one file, from ONE set of cached
mappings and ONE raw energy record:

  baseline_external_parity   Task 1's conventional-ECC number, produced by the
                             same `ecc.external_parity()` Task 1 calls -- the
                             value `bash run.sh baseline` writes, to the digit.
  embedded_ecc               Task 2: parity inside the stored weights, no
                             external parity. DRAM weight traffic is the FULL
                             codeword traffic Timeloop counts (the parity is
                             read and corrected, never discarded first) and the
                             external-parity term is zero. `eccenergy/embedded.py`
                             has the layout and why it is not a modelling choice.

The reconstruction placements stay `not_implemented` (Tasks 3-5).

WHAT IS HELD FIXED, AND CHECKED RATHER THAN ASSERTED
-----------------------------------------------------
Mapping, on-chip widths, access counts and MAC behaviour are identical for the
two arms because both are arithmetic on the same `Raw` record. The result file
proves it instead of saying it:

  fixed_mapping_shared_across_variants      the same mapping ids behind both
  non_dram_components_match_task1_baseline  every non-DRAM component equal, exactly
  dram_difference_is_exactly_the_external_parity
  embedded_reads_complete_codeword          bits billed = weight_bits x DRAM weight
                                            reads; nothing external; no K/N cut
  embedded_layout_hand_check                the codeword walk agrees with the closed form
  embedded_matches_sweep_figure_arm         the JSON and the figure's bar agree
  evaluation_only_rerun                     no mapping was generated by this run

WHAT IS OUTSIDE THE COMPARISON
------------------------------
ECC codec (decode / correction) energy. Task 2 says not to change it silently,
so it is charged to NEITHER arm here and every file says so; `ECC_DECODE=1`
affects the sweep figures only and triggers a warning here. No inference-
accuracy claim is made -- what the LSB overwrite does to accuracy is the
Input_Embedding study's question, not this one's.

WHY THE PHASE IS ALWAYS `Pre`
-----------------------------
Nothing about the embedded arm changes what the mapper sees: weights are
`weight_bits` wide in DRAM and on chip under both arms, so there is no reduced
representation to optimise for. The mappings are Task 1's, reused unchanged.
"""
from __future__ import annotations

import math

from ..archs import accumulator_bits, load_provenance
from ..ecc import embedded_dram, external_parity
from ..energy import plot_cats
from ..results_store import ResultBuilder, Variant
from . import audit
from .baseline import RECONSTRUCTION_PLACEMENTS
from .common import Session

EXPERIMENT = "task2_embedded_ecc_dram_only"

#: The one component the two arms differ in. Written explicitly as 0.0 for the
#: embedded arm so a reader sees "zero", not "missing".
PARITY_KEY = "DRAM external BCH parity"
DRAM_KEYS = ("DRAM", PARITY_KEY)

CODEC_NOTE = (
    "ECC codec (decode/correction) energy is OUTSIDE this comparison: it is "
    "charged to neither arm (Task 2: do not silently change ECC codec energy). "
    "Note that the arms would decode different numbers of codewords -- the "
    "baseline packs whole weights into a separately stored codeword, the "
    "embedded layout cuts the weight bit stream itself -- so a codec cost would "
    "not cancel; it is simply not costed until a characterised codec energy is "
    "adopted. ECC_DECODE affects the sweep figures only.")


def _recon_placeholders(builder):
    for name, description in RECONSTRUCTION_PLACEMENTS:
        builder.add(Variant(
            name, kind="reconstruction", status="not_implemented",
            unavailable_reason=(
                f"Tasks 3-5 have not been implemented. This entry names the "
                f"placement ({description}) so the document shape is final, but "
                f"no reconstruction has been evaluated."),
            label=description))


def task2_checks(builder, cfg, raw, base_components, emb_components, e_parity,
                 edetail, sweep_arm_total=None, newly_mapped=0, raw_cache_hit=None):
    """The checks that make Task 2's claim -- "only DRAM moved" -- auditable.

    Kept free of the Session so the offline test can drive it with a synthetic
    `Raw`. `sweep_arm_total` is the embedded bar of `ecc.build_stacks()` for the
    same record, or None to skip that comparison.
    """
    # 1. every non-DRAM component is identical, to the last digit
    names = sorted(set(base_components) | set(emb_components))
    pairs = {c: {"baseline": base_components.get(c, 0.0),
                 "embedded": emb_components.get(c, 0.0)}
             for c in names if c not in DRAM_KEYS}
    builder.check(
        "non_dram_components_match_task1_baseline",
        all(p["baseline"] == p["embedded"] for p in pairs.values()),
        {"components": pairs,
         "rule": ("exact equality -- both arms are arithmetic on ONE raw record, "
                  "so any difference outside DRAM is a bug, not a result")})

    # 2. the DRAM difference is the external parity and nothing else
    base_dram = sum(base_components.get(c, 0.0) for c in DRAM_KEYS)
    emb_dram = sum(emb_components.get(c, 0.0) for c in DRAM_KEYS)
    diff = base_dram - emb_dram
    builder.check(
        "dram_difference_is_exactly_the_external_parity",
        math.isclose(diff, e_parity, rel_tol=1e-12, abs_tol=1e-6),
        {"baseline_dram_pJ": base_dram, "embedded_dram_pJ": emb_dram,
         "difference_pJ": diff, "external_parity_pJ": e_parity,
         "timeloop_dram_pJ_both_arms": emb_components.get("DRAM", 0.0)})

    # 3. the complete codeword is read: every bit of every weight read is billed
    tr = edetail["traffic"]
    expect_bits = raw.dram_w_reads * cfg.weight_bits
    builder.check(
        "embedded_reads_complete_codeword",
        (math.isclose(tr["payload_bits_read"], expect_bits, rel_tol=1e-12, abs_tol=1e-6)
         and tr["external_bits"] == 0.0
         and edetail["dram_weight_energy_pJ"] == raw.e_dram_w),
        {"dram_weight_reads": raw.dram_w_reads, "weight_bits": cfg.weight_bits,
         "bits_billed": tr["payload_bits_read"], "bits_expected": expect_bits,
         "external_bits": tr["external_bits"],
         "dram_weight_energy_pJ": edetail["dram_weight_energy_pJ"],
         "rule": ("no K/N reduction at DRAM: the embedded parity is read and "
                  "corrected, not discarded before correction")})

    # 4. the layout arithmetic reconciles the long way
    builder.check("embedded_layout_hand_check", edetail["hand_check_passed"],
                  edetail["hand_check"])

    # 5. the figure and the JSON say the same thing
    emb_total = float(sum(emb_components.values()))
    if sweep_arm_total is not None:
        builder.check(
            "embedded_matches_sweep_figure_arm",
            math.isclose(sweep_arm_total, emb_total, rel_tol=1e-9, abs_tol=1e-3),
            {"sweep_figure_embedded_pJ": sweep_arm_total, "this_result_pJ": emb_total,
             "source": "ecc.build_stacks()['embedded'] on the same raw record"})

    # 6. evaluation-only: nothing was mapped by this run
    builder.check(
        "evaluation_only_rerun",
        bool(cfg.from_cache) or newly_mapped == 0,
        {"ECC_FROM_CACHE": bool(cfg.from_cache),
         "raw_energy_cache_hit": raw_cache_hit,
         "newly_mapped_shapes": newly_mapped,
         "meaning": ("passed: every mapping behind this result already existed; "
                     "the mapper was not invoked. Failed: this run generated "
                     "mappings -- re-run with --eval to produce the "
                     "evaluation-only rerun Task 2 asks for")})


def _report(cfg, arch, model, raw, base_total, emb_total, pdetail, edetail):
    acc, _ = accumulator_bits(arch, cfg)
    lay = edetail["layout"]
    ps = pdetail["stored"]
    es = edetail["stored"]
    pt = pdetail["traffic"]
    et = edetail["traffic"]
    prof = lay["parity_significance"]["parity_bits_per_weight_by_significance"]
    prof_s = ", ".join(f"{k} {v:.3f}" for k, v in prof.items())
    saving = (base_total - emb_total) / base_total * 100.0 if base_total else 0.0
    print(f"\n  --- {arch} / {model} : Task 2, embedded ECC vs conventional ECC "
          f"(DRAM effect only) ---")
    print(f"    precisions            : weight {cfg.weight_bits}b   "
          f"activation {cfg.activation_bits}b   accumulator {acc}b (published)")
    print(f"    code                  : BCH({lay['n']},{lay['k']}) t={cfg.code_t}   "
          f"{lay['parity_bits_per_codeword']}b parity per codeword")
    print(f"    embedded layout       : {lay['n']}-bit chunks of the weight bit stream -> "
          f"{lay['weights_per_codeword']:.4f} weights/codeword, period "
          f"{lay['period_codewords']} codewords = {lay['period_weights']} weights, "
          f"{lay['split_boundaries_per_period']} of {lay['period_codewords']} "
          f"boundaries split a weight")
    print(f"    parity per weight     : {prof_s}  (bits overwritten, by significance)")
    print(f"    payload               : {es['weights']:,} weights = "
          f"{es['payload_bytes']:,.0f} B   (both arms)")
    print(f"    {'':22s}  {'conventional (Task 1)':>24s}  {'embedded (Task 2)':>20s}")
    print(f"    stored codewords      : {ps['codewords']:>24,}  {es['codewords']:>20,}")
    print(f"    external parity       : {ps['parity_bytes']:>22,.0f} B  "
          f"{es['external_parity_bytes']:>18,.0f} B")
    print(f"    padding stored        : "
          f"{(ps['message_pad_bits'] + ps['tail_pad_bits']) / 8:>22,.0f} B  "
          f"{es['tail_pad_bits'] / 8:>18,.0f} B")
    print(f"    stored total          : {ps['stored_bytes']:>22,.0f} B  "
          f"{es['stored_bytes']:>18,.0f} B")
    print(f"    bits per weight       : {ps['stored_bits'] / ps['weights']:>24.4f}  "
          f"{es['bits_per_weight']:>20.4f}")
    print(f"    DRAM weight reads     : {raw.dram_w_reads:>24,.0f}  "
          f"{raw.dram_w_reads:>20,.0f}   (identical; refetch x{et['refetch_factor']:.2f})")
    print(f"    external DRAM words   : {pt['external_dram_words']:>24,.0f}  "
          f"{et['external_dram_words']:>20,.0f}")
    print(f"    DRAM weight energy    : {(raw.e_dram_w + pdetail['energy_pJ']) / 1e6:>21,.3f} uJ  "
          f"{edetail['dram_weight_energy_pJ'] / 1e6:>17,.3f} uJ")
    print(f"    total                 : {base_total / 1e6:>21,.3f} uJ  "
          f"{emb_total / 1e6:>17,.3f} uJ   -> saving {saving:.2f}%")
    print(f"    non-DRAM components   : identical by construction, checked")
    print(f"    hand checks           : baseline "
          f"{'PASS' if pdetail['hand_check_passed'] else 'FAIL'}   embedded "
          f"{'PASS' if edetail['hand_check_passed'] else 'FAIL'}")


def evaluate(cfg, ses, prov, arch, model, raw):
    """Build and write the Task 2 result for one (architecture, model)."""
    cats = plot_cats(cfg)
    base_series = raw.base.reindex(cats, fill_value=0.0)

    # ---- arm 1: Task 1's conventional baseline. Same function, same numbers.
    e_parity, pdetail = external_parity(cfg, raw)
    base_components = audit.components(base_series)
    base_components[PARITY_KEY] = e_parity
    base_total = float(sum(base_components.values()))

    # ---- arm 2: embedded. Same raw record; the external term is zero.
    e_external, edetail = embedded_dram(cfg, raw)
    emb_components = audit.components(base_series)
    emb_components[PARITY_KEY] = e_external
    emb_total = float(sum(emb_components.values()))

    builder = ResultBuilder(cfg, ses.results, arch, model,
                            experiment=EXPERIMENT, fixed_mapping=True)
    mapping_ids = audit.mapping_ids_of(raw)

    builder.add(Variant(
        "baseline_external_parity", kind="baseline", status="evaluated",
        total_energy_pJ=base_total, energy_by_component_pJ=base_components,
        mapping_ids=mapping_ids,
        label="Conventional ECC, BCH parity external in DRAM",
        extra={"external_parity_accounting": pdetail,
               "timeloop_energy_pJ": float(raw.total),
               "dram_weight_reads": raw.dram_w_reads,
               "dram_weight_energy_pJ": raw.e_dram_w,
               "ecc_codec_energy": CODEC_NOTE}))
    builder.add(Variant(
        "embedded_ecc", kind="embedded", status="evaluated",
        total_energy_pJ=emb_total, energy_by_component_pJ=emb_components,
        mapping_ids=mapping_ids,
        label="Embedded ECC, parity inside the stored weights, no external parity",
        extra={"embedded_dram_accounting": edetail,
               "timeloop_energy_pJ": float(raw.total),
               "dram_weight_reads": raw.dram_w_reads,
               "dram_weight_energy_pJ": raw.e_dram_w,
               "dram_energy_removed_vs_conventional_pJ": e_parity,
               "what_changed": ("DRAM only: the external-parity traffic of the "
                                "conventional baseline is gone. Mapping, on-chip "
                                "widths, access counts, NoC and MAC energy are the "
                                "same numbers as the baseline variant in this file."),
               "ecc_codec_energy": CODEC_NOTE}))
    _recon_placeholders(builder)

    # ---- the checks that make "only DRAM moved" auditable -------------------
    stack = ses.stacks.get(arch, {}).get(model)
    arm_total = None
    if stack is not None and "embedded" in getattr(stack, "columns", []):
        if cfg.decode_enabled or cfg.weak_enabled:
            builder.warn(
                "the sweep figure's embedded arm carries ECC decode and/or weak-ECC "
                "terms (ECC_DECODE / ECC_WEAK); this experiment keeps codec energy "
                "outside the comparison, so the figure and this file differ by design")
        else:
            arm_total = float(stack["embedded"].sum())
    mapper = ses.mappers.get(arch)
    task2_checks(builder, cfg, raw, base_components, emb_components, e_parity,
                 edetail, sweep_arm_total=arm_total,
                 newly_mapped=(getattr(mapper, "n_mapped", 0) if mapper is not None else 0),
                 raw_cache_hit=(mapper is None))

    # ---- Task 1's checks and caveats, so the baseline variant is as audited
    # here as in its own file --------------------------------------------------
    arch_report = audit.common_checks(builder, cfg, arch, raw, pdetail, mapping_ids)
    audit.common_caveats(builder, cfg, arch, raw, pdetail)
    builder.approximate(edetail["traffic"]["method"])
    builder.approximate(CODEC_NOTE)
    builder.approximate(
        "This is a fixed-mapping, DRAM-only comparison. It credits no on-chip "
        "saving to the embedded arm and makes no inference-accuracy claim about "
        "overwriting weight LSBs with parity.")
    if cfg.decode_enabled:
        builder.warn("ECC_DECODE=1: decode energy is drawn in the sweep figures but "
                     "is deliberately not charged to either arm in this file.")
    audit.common_detail(builder, cfg, ses, arch, model, raw, arch_report, prov)

    _report(cfg, arch, model, raw, base_total, emb_total, pdetail, edetail)
    path = builder.write()
    print(f"    -> {path}")
    return path


def run(cfg):
    if cfg.phase != "Pre":
        raise SystemExit(
            f"ECC_PHASE={cfg.phase} but the Task 2 embedded-ECC result is a `Pre` "
            f"result by construction: the embedded arm changes nothing the mapper "
            f"sees, so no mapping could have been optimised for it.")

    ses = Session(cfg).setup()
    ses.collect_all()
    prov = load_provenance()
    written = []
    for arch in cfg.archs:
        for model, raw in (ses.raws.get(arch) or {}).items():
            written.append(evaluate(cfg, ses, prov, arch, model, raw))

    if not written:
        raise SystemExit("nothing was evaluated; see the [skip] lines above")

    print("\n" + "=" * 78)
    print(f"Task 2 embedded ECC: {len(written)} result file(s) written under "
          f"{ses.results.evaluation}")
    print("Each holds the conventional baseline AND the embedded-ECC variant from the")
    print("same cached mappings; the reconstruction placements stay unavailable.")
    print("Only the DRAM component differs between the two arms -- checked, not asserted.")
    print("=" * 78)
    return written
